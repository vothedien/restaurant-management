CREATE TABLE IF NOT EXISTS model_versions (
    model_version_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name         varchar(120) NOT NULL,
    algorithm          varchar(100) NOT NULL,
    version_label      varchar(40)  NOT NULL,
    parameters         jsonb        NOT NULL DEFAULT '{}'::jsonb,
    feature_config     jsonb        NOT NULL DEFAULT '{}'::jsonb,
    trained_at         timestamptz,
    training_data_from date,
    training_data_to   date,
    status             varchar(20)  NOT NULL DEFAULT 'INACTIVE',
    created_by         bigint,
    notes              text,
    created_at         timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_model_versions_name_version UNIQUE (model_name, version_label),
    CONSTRAINT fk_model_versions_created_by FOREIGN KEY (created_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_model_versions_parameters_object
        CHECK (jsonb_typeof(parameters) = 'object'),
    CONSTRAINT ck_model_versions_feature_config_object
        CHECK (jsonb_typeof(feature_config) = 'object'),
    CONSTRAINT ck_model_versions_training_dates
        CHECK (training_data_to IS NULL OR training_data_from IS NULL
               OR training_data_to >= training_data_from),
    CONSTRAINT ck_model_versions_status
        CHECK (status IN ('TRAINING', 'ACTIVE', 'INACTIVE', 'FAILED', 'ARCHIVED'))
);

CREATE TABLE IF NOT EXISTS model_metrics (
    metric_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version_id  bigint        NOT NULL,
    metric_name       varchar(40)   NOT NULL,
    metric_value      numeric(18,6) NOT NULL,
    dataset_scope     varchar(20)   NOT NULL,
    calculated_at     timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_model_metrics_version_name_scope
        UNIQUE (model_version_id, metric_name, dataset_scope),
    CONSTRAINT fk_model_metrics_version FOREIGN KEY (model_version_id)
        REFERENCES model_versions (model_version_id) ON DELETE CASCADE,
    CONSTRAINT ck_model_metrics_scope
        CHECK (dataset_scope IN ('TRAIN', 'VALIDATION', 'TEST', 'PRODUCTION'))
);

CREATE TABLE IF NOT EXISTS forecast_runs (
    forecast_run_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version_id     bigint      NOT NULL,
    forecast_start_date  date        NOT NULL,
    forecast_end_date    date        NOT NULL,
    horizon_days         integer     NOT NULL,
    trigger_type         varchar(20) NOT NULL,
    status               varchar(20) NOT NULL DEFAULT 'PENDING',
    generated_by         bigint,
    generated_at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    error_message        text,

    CONSTRAINT fk_forecast_runs_model_version FOREIGN KEY (model_version_id)
        REFERENCES model_versions (model_version_id) ON DELETE RESTRICT,
    CONSTRAINT fk_forecast_runs_generated_by FOREIGN KEY (generated_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_forecast_runs_dates CHECK (forecast_end_date >= forecast_start_date),
    CONSTRAINT ck_forecast_runs_horizon CHECK (horizon_days > 0),
    CONSTRAINT ck_forecast_runs_trigger
        CHECK (trigger_type IN ('MANUAL', 'SCHEDULED')),
    CONSTRAINT ck_forecast_runs_status
        CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_forecast_runs_error
        CHECK (status <> 'FAILED' OR error_message IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS forecast_results (
    forecast_result_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forecast_run_id    bigint        NOT NULL,
    dish_id            bigint        NOT NULL,
    forecast_date      date          NOT NULL,
    predicted_qty      numeric(14,3) NOT NULL,
    lower_bound        numeric(14,3),
    upper_bound        numeric(14,3),
    actual_qty         numeric(14,3),

    CONSTRAINT uq_forecast_results_run_dish_date
        UNIQUE (forecast_run_id, dish_id, forecast_date),
    CONSTRAINT fk_forecast_results_run FOREIGN KEY (forecast_run_id)
        REFERENCES forecast_runs (forecast_run_id) ON DELETE CASCADE,
    CONSTRAINT fk_forecast_results_dish FOREIGN KEY (dish_id)
        REFERENCES dishes (dish_id) ON DELETE RESTRICT,
    CONSTRAINT ck_forecast_results_predicted CHECK (predicted_qty >= 0),
    CONSTRAINT ck_forecast_results_lower CHECK (lower_bound IS NULL OR lower_bound >= 0),
    CONSTRAINT ck_forecast_results_upper
        CHECK (upper_bound IS NULL OR upper_bound >= predicted_qty),
    CONSTRAINT ck_forecast_results_bounds
        CHECK (lower_bound IS NULL OR lower_bound <= predicted_qty),
    CONSTRAINT ck_forecast_results_actual CHECK (actual_qty IS NULL OR actual_qty >= 0)
);

CREATE TABLE IF NOT EXISTS replenishment_proposals (
    proposal_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_number    varchar(40) NOT NULL,
    forecast_run_id    bigint      NOT NULL,
    planning_start_date date       NOT NULL,
    planning_end_date  date        NOT NULL,
    status             varchar(20) NOT NULL DEFAULT 'DRAFT',
    created_at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by        bigint,
    reviewed_at        timestamptz,
    decision_reason    text,

    CONSTRAINT uq_replenishment_proposals_number UNIQUE (proposal_number),
    CONSTRAINT fk_replenishment_proposals_run FOREIGN KEY (forecast_run_id)
        REFERENCES forecast_runs (forecast_run_id) ON DELETE RESTRICT,
    CONSTRAINT fk_replenishment_proposals_reviewed_by FOREIGN KEY (reviewed_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_replenishment_proposals_dates
        CHECK (planning_end_date >= planning_start_date),
    CONSTRAINT ck_replenishment_proposals_status
        CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'APPROVED', 'REJECTED', 'ORDERED')),
    CONSTRAINT ck_replenishment_proposals_review
        CHECK (
            status NOT IN ('APPROVED', 'REJECTED')
            OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
        )
);

CREATE TABLE IF NOT EXISTS replenishment_proposal_items (
    proposal_item_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id               bigint        NOT NULL,
    ingredient_id             bigint        NOT NULL,
    forecast_demand_qty       numeric(14,3) NOT NULL,
    available_stock_qty       numeric(14,3) NOT NULL,
    incoming_qty              numeric(14,3) NOT NULL,
    safety_stock_qty          numeric(14,3) NOT NULL,
    lead_time_days_snapshot   integer       NOT NULL,
    suggested_qty             numeric(14,3) NOT NULL,
    adjusted_qty              numeric(14,3),
    final_qty                 numeric(14,3)
        GENERATED ALWAYS AS (COALESCE(adjusted_qty, suggested_qty)) STORED,
    preferred_supplier_id     bigint,
    adjustment_reason         text,

    CONSTRAINT uq_replenishment_items_proposal_ingredient
        UNIQUE (proposal_id, ingredient_id),
    CONSTRAINT fk_replenishment_items_proposal FOREIGN KEY (proposal_id)
        REFERENCES replenishment_proposals (proposal_id) ON DELETE CASCADE,
