

BEGIN;

SET TIME ZONE 'Asia/Ho_Chi_Minh';

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS restaurant_ai;
SET search_path TO restaurant_ai, public;

-- =============================================================================
-- 1. TÀI KHOẢN, PHÂN QUYỀN VÀ NHẬT KÝ
-- =============================================================================

CREATE TABLE IF NOT EXISTS users (
    user_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        varchar(50)  NOT NULL,
    password_hash   varchar(255) NOT NULL,
    full_name       varchar(120) NOT NULL,
    email           varchar(150),
    phone           varchar(20),
    status          varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    last_login_at   timestamptz,
    created_at      timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

CREATE TABLE IF NOT EXISTS roles (
    role_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code       varchar(50)  NOT NULL,
    role_name       varchar(100) NOT NULL,
    description     text,
    is_active       boolean      NOT NULL DEFAULT true,

    CONSTRAINT uq_roles_role_code UNIQUE (role_code)
);

CREATE TABLE IF NOT EXISTS permissions (
    permission_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code varchar(80)  NOT NULL,
    permission_name varchar(120) NOT NULL,
    description     text,

    CONSTRAINT uq_permissions_permission_code UNIQUE (permission_code)
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id         bigint      NOT NULL,
    role_id         bigint      NOT NULL,
    assigned_by     bigint,
    assigned_at     timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id)
        REFERENCES roles (role_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_assigned_by FOREIGN KEY (assigned_by)
        REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id         bigint NOT NULL,
    permission_id   bigint NOT NULL,

    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role FOREIGN KEY (role_id)
        REFERENCES roles (role_id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id)
        REFERENCES permissions (permission_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS audit_logs (
    audit_log_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id   bigint,
    action_code     varchar(80) NOT NULL,
    entity_type     varchar(80) NOT NULL,
    entity_id       varchar(80),
    description     text,
    old_values      jsonb,
    new_values      jsonb,
    ip_address      inet,
    occurred_at     timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_audit_logs_actor FOREIGN KEY (actor_user_id)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_audit_logs_old_values_object
        CHECK (old_values IS NULL OR jsonb_typeof(old_values) = 'object'),
    CONSTRAINT ck_audit_logs_new_values_object
        CHECK (new_values IS NULL OR jsonb_typeof(new_values) = 'object')
);

-- =============================================================================
-- 2. ĐƠN VỊ, NGUYÊN LIỆU, BÀN, MÓN ĂN VÀ CÔNG THỨC
-- =============================================================================

CREATE TABLE IF NOT EXISTS units (
    unit_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_code       varchar(20) NOT NULL,
    unit_name       varchar(80) NOT NULL,
    dimension       varchar(20) NOT NULL,
    is_active       boolean     NOT NULL DEFAULT true,

    CONSTRAINT uq_units_unit_code UNIQUE (unit_code),
    CONSTRAINT ck_units_dimension
        CHECK (dimension IN ('MASS', 'VOLUME', 'COUNT', 'LENGTH', 'OTHER'))
);

CREATE TABLE IF NOT EXISTS unit_conversions (
    conversion_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_unit_id    bigint        NOT NULL,
    to_unit_id      bigint        NOT NULL,
    factor          numeric(18,6) NOT NULL,

    CONSTRAINT uq_unit_conversions_pair UNIQUE (from_unit_id, to_unit_id),
    CONSTRAINT fk_unit_conversions_from FOREIGN KEY (from_unit_id)
        REFERENCES units (unit_id) ON DELETE RESTRICT,
    CONSTRAINT fk_unit_conversions_to FOREIGN KEY (to_unit_id)
        REFERENCES units (unit_id) ON DELETE RESTRICT,
    CONSTRAINT ck_unit_conversions_different_units CHECK (from_unit_id <> to_unit_id),
    CONSTRAINT ck_unit_conversions_factor_positive CHECK (factor > 0)
);

CREATE TABLE IF NOT EXISTS ingredients (
    ingredient_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_code         varchar(40)   NOT NULL,
    ingredient_name         varchar(150)  NOT NULL,
    base_unit_id            bigint        NOT NULL,
    manages_lot             boolean       NOT NULL DEFAULT true,
    default_shelf_life_days integer,
    minimum_stock_qty       numeric(14,3) NOT NULL DEFAULT 0,
    safety_stock_qty        numeric(14,3) NOT NULL DEFAULT 0,
    status                  varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at              timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_ingredients_code UNIQUE (ingredient_code),
    CONSTRAINT fk_ingredients_base_unit FOREIGN KEY (base_unit_id)
        REFERENCES units (unit_id) ON DELETE RESTRICT,
    CONSTRAINT ck_ingredients_shelf_life
        CHECK (default_shelf_life_days IS NULL OR default_shelf_life_days >= 0),
    CONSTRAINT ck_ingredients_minimum_stock CHECK (minimum_stock_qty >= 0),
    CONSTRAINT ck_ingredients_safety_stock CHECK (safety_stock_qty >= 0),
    CONSTRAINT ck_ingredients_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE IF NOT EXISTS dining_tables (
    table_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_code       varchar(30) NOT NULL,
    table_name       varchar(80),
    capacity         integer     NOT NULL,
    status           varchar(20) NOT NULL DEFAULT 'AVAILABLE',
    created_at       timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_dining_tables_code UNIQUE (table_code),
    CONSTRAINT ck_dining_tables_capacity CHECK (capacity > 0),
    CONSTRAINT ck_dining_tables_status
        CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'RESERVED', 'INACTIVE'))
);

CREATE TABLE IF NOT EXISTS menu_categories (
    category_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code    varchar(40)  NOT NULL,
    category_name    varchar(120) NOT NULL,
    description      text,
    display_order    integer      NOT NULL DEFAULT 0,
    status           varchar(20)  NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT uq_menu_categories_code UNIQUE (category_code),
    CONSTRAINT ck_menu_categories_display_order CHECK (display_order >= 0),
    CONSTRAINT ck_menu_categories_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE IF NOT EXISTS dishes (
    dish_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_code        varchar(40)   NOT NULL,
    dish_name        varchar(150)  NOT NULL,
    category_id      bigint        NOT NULL,
    selling_price    numeric(14,2) NOT NULL,
    description      text,
    status           varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at       timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_dishes_code UNIQUE (dish_code),
    CONSTRAINT fk_dishes_category FOREIGN KEY (category_id)
        REFERENCES menu_categories (category_id) ON DELETE RESTRICT,
    CONSTRAINT ck_dishes_selling_price CHECK (selling_price >= 0),
    CONSTRAINT ck_dishes_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'SOLD_OUT'))
);

CREATE TABLE IF NOT EXISTS recipe_versions (
    recipe_version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_id            bigint       NOT NULL,
    version_no         integer      NOT NULL,
    status             varchar(20)  NOT NULL DEFAULT 'DRAFT',
    effective_from     date,
    effective_to       date,
    notes              text,
    created_by         bigint,
    created_at         timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_recipe_versions_dish_version UNIQUE (dish_id, version_no),
    CONSTRAINT fk_recipe_versions_dish FOREIGN KEY (dish_id)
        REFERENCES dishes (dish_id) ON DELETE RESTRICT,
    CONSTRAINT fk_recipe_versions_created_by FOREIGN KEY (created_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_recipe_versions_version_no CHECK (version_no > 0),
    CONSTRAINT ck_recipe_versions_dates
        CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from),
    CONSTRAINT ck_recipe_versions_status
        CHECK (status IN ('DRAFT', 'ACTIVE', 'INACTIVE', 'EXPIRED'))
);

CREATE TABLE IF NOT EXISTS recipe_items (
    recipe_item_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_version_id bigint        NOT NULL,
    ingredient_id     bigint        NOT NULL,
    quantity          numeric(14,3) NOT NULL,
    unit_id           bigint        NOT NULL,
    base_quantity     numeric(14,3) NOT NULL,

    CONSTRAINT uq_recipe_items_recipe_ingredient
        UNIQUE (recipe_version_id, ingredient_id),
    CONSTRAINT fk_recipe_items_recipe_version FOREIGN KEY (recipe_version_id)
        REFERENCES recipe_versions (recipe_version_id) ON DELETE CASCADE,
    CONSTRAINT fk_recipe_items_ingredient FOREIGN KEY (ingredient_id)
        REFERENCES ingredients (ingredient_id) ON DELETE RESTRICT,
    CONSTRAINT fk_recipe_items_unit FOREIGN KEY (unit_id)
        REFERENCES units (unit_id) ON DELETE RESTRICT,
    CONSTRAINT ck_recipe_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_recipe_items_base_quantity CHECK (base_quantity > 0)
);

-- =============================================================================
-- 3. ORDER, BẾP VÀ THANH TOÁN
-- =============================================================================

CREATE TABLE IF NOT EXISTS orders (
    order_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number        varchar(40)   NOT NULL,
    table_id            bigint        NOT NULL,
    opened_by           bigint        NOT NULL,
    status              varchar(20)   NOT NULL DEFAULT 'OPEN',
    opened_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at             timestamptz,
    completed_at        timestamptz,
    subtotal_amount     numeric(14,2) NOT NULL DEFAULT 0,
    notes               text,
    cancelled_by        bigint,
    cancelled_at        timestamptz,
    cancellation_reason text,

    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    CONSTRAINT fk_orders_table FOREIGN KEY (table_id)
        REFERENCES dining_tables (table_id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_opened_by FOREIGN KEY (opened_by)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_cancelled_by FOREIGN KEY (cancelled_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_orders_subtotal CHECK (subtotal_amount >= 0),
    CONSTRAINT ck_orders_status
        CHECK (status IN ('OPEN', 'SENT', 'IN_PROGRESS', 'COMPLETED', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_orders_sent_at CHECK (sent_at IS NULL OR sent_at >= opened_at),
    CONSTRAINT ck_orders_completed_at
        CHECK (completed_at IS NULL OR completed_at >= opened_at),
    CONSTRAINT ck_orders_cancellation
        CHECK (
            (status <> 'CANCELLED')
            OR (cancelled_at IS NOT NULL AND cancellation_reason IS NOT NULL)
        )
);

CREATE TABLE IF NOT EXISTS order_items (
    order_item_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            bigint        NOT NULL,
    dish_id             bigint        NOT NULL,
    recipe_version_id   bigint,
    quantity            integer       NOT NULL,
    unit_price          numeric(14,2) NOT NULL,
    line_amount         numeric(14,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    status              varchar(20)   NOT NULL DEFAULT 'PENDING',
    notes               text,
    sent_at             timestamptz,
    completed_at        timestamptz,
    cancelled_by        bigint,
    cancelled_at        timestamptz,
    cancellation_reason text,

    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_dish FOREIGN KEY (dish_id)
        REFERENCES dishes (dish_id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_recipe_version FOREIGN KEY (recipe_version_id)
        REFERENCES recipe_versions (recipe_version_id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_cancelled_by FOREIGN KEY (cancelled_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_items_status
        CHECK (status IN ('PENDING', 'SENT', 'PREPARING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_order_items_cancellation
        CHECK (
            (status <> 'CANCELLED')
            OR (cancelled_at IS NOT NULL AND cancellation_reason IS NOT NULL)
        )
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_number  varchar(40)   NOT NULL,
    order_id        bigint        NOT NULL,
    amount          numeric(14,2) NOT NULL,
    payment_method  varchar(20)   NOT NULL,
    received_by     bigint        NOT NULL,
    paid_at         timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes           text,

    CONSTRAINT uq_payments_number UNIQUE (payment_number),
    CONSTRAINT uq_payments_order UNIQUE (order_id),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE RESTRICT,
    CONSTRAINT fk_payments_received_by FOREIGN KEY (received_by)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_method
        CHECK (payment_method IN ('CASH', 'CARD', 'BANK_TRANSFER', 'E_WALLET'))
);

