CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code   varchar(40)  NOT NULL,
    supplier_name   varchar(180) NOT NULL,
    contact_name    varchar(120),
    phone           varchar(20),
    email           varchar(150),
    address         text,
    tax_code        varchar(30),
    status          varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at      timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_suppliers_code UNIQUE (supplier_code),
    CONSTRAINT ck_suppliers_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

CREATE TABLE IF NOT EXISTS supplier_ingredients (
    supplier_ingredient_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id                  bigint        NOT NULL,
    ingredient_id                bigint        NOT NULL,
    supplier_sku                 varchar(80),
    purchase_unit_id             bigint        NOT NULL,
    base_qty_per_purchase_unit   numeric(14,3) NOT NULL,
    lead_time_days               integer       NOT NULL DEFAULT 0,
    minimum_order_qty            numeric(14,3) NOT NULL DEFAULT 1,
    latest_unit_price            numeric(14,2),
    is_preferred                 boolean       NOT NULL DEFAULT false,
    is_active                    boolean       NOT NULL DEFAULT true,

    CONSTRAINT uq_supplier_ingredients_supplier_ingredient
        UNIQUE (supplier_id, ingredient_id),
    CONSTRAINT fk_supplier_ingredients_supplier FOREIGN KEY (supplier_id)
        REFERENCES suppliers (supplier_id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_ingredients_ingredient FOREIGN KEY (ingredient_id)
        REFERENCES ingredients (ingredient_id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_ingredients_purchase_unit FOREIGN KEY (purchase_unit_id)
        REFERENCES units (unit_id) ON DELETE RESTRICT,
    CONSTRAINT ck_supplier_ingredients_base_qty CHECK (base_qty_per_purchase_unit > 0),
    CONSTRAINT ck_supplier_ingredients_lead_time CHECK (lead_time_days >= 0),
    CONSTRAINT ck_supplier_ingredients_minimum_order CHECK (minimum_order_qty > 0),
    CONSTRAINT ck_supplier_ingredients_price
        CHECK (latest_unit_price IS NULL OR latest_unit_price >= 0)
);

